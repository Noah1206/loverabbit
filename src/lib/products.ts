export type CardTone =
  | "ember" | "rose" | "velvet" | "warning" | "promise" | "rain" | "midnight"
  | "blush" | "secret" | "candle" | "peach" | "timing" | "starlight";

export interface Product {
  id: string;
  badge: string;
  title: string;
  emoji: string;
  desc: string;
  grad: [string, string];
  tags: ("popular" | "new")[];
  price: number; // 판매가(원) — 단품 티어: 9,900 / 12,000 (상한 12,000원, 2026-08-27)
  shortLabel: string; // 리딩 폼 선택 칩에 쓰는 짧은 이름
  needsPartner: boolean; // 상대방 생년월일이 필요한 리딩인지
  promptLabel: string; // AI에 전달하는 리딩 종류 설명
  cardCopy: string; // 홈 카드 오버레이 문구
  tone: CardTone; // 홈 카드 색 톤 (data-tone)
  ctaLabel: string; // 홈 카드와 상세 하단 버튼에 함께 쓰는 상품별 행동 문구
  ctaHook: string; // 상세 하단 버튼 위에 노출하는 짧은 기대효과
  // ── 상세 판매 페이지 ──
  headline: string; // 질문형 후킹
  sub: string;
  scoreLabel: string; // 게이지 이름 (예: 재회 가능성)
  gaugeCaption: string;
  meterLabels: string[]; // 게이지 단계 연출 (5개)
  keywords: string[]; // 리포트 키워드 칩 (4~5개)
  audience: string[]; // 누가 보면 좋을까요
  principles: [string, string][]; // 풀이 원리 (상세 페이지에서는 2026-08-25 에 내렸다. 약속 검사에는 계속 쓴다)
  /**
   * 전체 리포트 구성 표의 세 줄. 목차(toc)에 실제로 있는 장만 요약한다 —
   * 여기에 목차에 없는 약속을 적으면 산 사람이 산 리포트가 아니게 된다.
   */
  reportFacets: { judgement: string; risk: string; action: string };
  toc: string[]; // 이런 결과를 받아요
  /**
   * 이 상품이 파는 앞날의 길이(달). 판매 문구가 숫자로 앞날을 약속할 때만 적는다.
   *
   * 계산이 감당하는 길이(saju-facts UPCOMING_MONTHS + 다음 해)보다 길면
   * reading-scope 가 목차와 이름을 좁혀 내보내고, 테스트가 그 사실을 알린다.
   * 문구가 이 값보다 긴 앞날을 말하면 테스트가 실패한다 — 약속이 코드 모르게
   * 자라지 않게 하는 자리다.
   */
  timeHorizonMonths?: number;
}

