// 전환 한 건의 이름표.
//
// 브라우저와 서버가 같은 결제를 각자 한 번씩 보낸다. 그래야 픽셀이 막힌
// 사람도, 서버 설정이 빠진 경우도 어느 한쪽으로는 남는다. 대신 두 쪽이 **같은**
// 이름표를 써야 Meta 가 한 건으로 합친다 — 무작위로 만들면 매출이 두 배로 보인다.
//
// 그래서 이 함수가 클라이언트와 서버 양쪽에 있다. 한쪽에만 두면 다음에 고치는
// 사람이 반대쪽을 못 보고 규칙을 어긴다.

/**
 * @param orderRef 주문을 가리키는 값. 계좌이체는 주문 번호(숫자), 포트원은
 *   결제 번호(LRP_...)다. 둘 다 그 결제에만 붙는 값이고 브라우저와 서버가
 *   똑같이 알고 있다.
 */
export function purchaseEventId(orderRef: string | number): string {
  return `order-${orderRef}`;
}
