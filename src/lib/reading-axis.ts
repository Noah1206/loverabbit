// 이 리포트가 답해야 하는 물음 — 상품마다 다른 축.
//
// 열네 개 상품이 같은 지시문과 같은 규칙 표를 쓴다. 상품을 가르는 것은 목차 제목
// 하나뿐이었고, 그래서 속궁합 리포트가 재회 리포트와 같은 결로 나왔다. 목차는
// 절마다 무엇을 다룰지는 말해 주지만 **리포트 전체가 어디를 향하는지**는 말하지
// 않는다. 그 자리를 여기서 채운다.
//
// 규칙 표(reading-rules.ts)와 역할이 다르다. 헷갈리면 안 된다.
//   규칙  — 무엇을 주장해도 되는가. 명리의 경계다. 사람이 근거를 갖고 넓힌다.
//   축    — 그 주장을 어느 물음 쪽으로 향하게 쓸 것인가. 표현의 문제다.
//
// **축은 규칙을 이기지 못한다.** 축이 온도를 물어도 규칙에 없는 온도 판단은
// 만들지 않는다. 축이 하는 일은 이미 켜진 규칙 중에서 **이 상품의 물음에 가장
// 가까운 것부터 고르게** 하는 것뿐이다.

export interface ProductAxis {
  /** 이 상품이 답하는 물음 한 줄 */
  question: string;
  /** 리포트 전체가 끝까지 붙드는 축. 절마다 이 중 하나에는 닿아야 한다 */
  axes: string[];
  /** 장면을 어디에서 고르는가 */
  stage: string;
  /** 다른 상품의 물음 — 새면 안 되는 곳 */
  avoid: string[];
  /** 이 상품의 말 */
  vocabulary: string;
  /**
   * 표현의 선. **없으면 없는 대로 간다** — 비어 있으면 그 칸 자체가 안 나간다.
   *
   * 여기 적는 것은 이 상품에만 걸리는 선이다. 어느 상품에나 걸리는 것(의료·법률·
   * 재무 판정, 위기 신호)은 지시문의 LIMITS 가 이미 갖고 있으므로 옮겨 적지 않는다.
   */
  line?: string[];
  /**
   * 이 상품이 지수를 절 하나로 파는가.
   *
   * 켜면 발급 때 계산한 지수(saju-score.ts)가 프롬프트로 간다. 안 켜면 안 간다.
   *
   * 켜는 기준은 하나다 — **목차가 그 숫자를 팔고 있는가.** 속궁합은 "3장 01.
   * 속궁합 지수" 라는 절을 파는데, 정작 그 절을 쓰는 동안 모델은 숫자를 못 봤다.
   * 그래서 모델이 "중상 정도" 같은 등급을 따로 지어냈고, 화면에 찍히는 지수와
   * 본문의 등급이 각자 정해진 값이라 서로 어긋날 수 있었다. 한 리포트가 같은
   * 물음에 두 개의 답을 갖고 있던 셈이다.
   *
   * 숫자를 준다고 해석이 열리는 것은 아니다. 지수는 계산값의 요약이지 명리
   * 판단이 아니라서, 판단은 여전히 matched_rules 에서만 나온다. 지시문이 그
   * 경계를 함께 적어 보낸다.
   */
  usesScore?: boolean;
}

