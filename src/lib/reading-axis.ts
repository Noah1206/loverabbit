export function axisFor(productId: string | undefined): ProductAxis | null {
  return (productId && READING_AXES[productId]) || null;
}

/** 프롬프트에 실을 꼴. 축이 없으면 아무것도 싣지 않는다 — 예전 그대로 돌아간다. */
export function axisForPrompt(productId: string | undefined) {
  const axis = axisFor(productId);
  if (!axis) return null;
  return {
    question: axis.question,
    axes: axis.axes,
    stage: axis.stage,
    avoid: axis.avoid,
    vocabulary: axis.vocabulary,
    // 선이 없으면 빈 칸을 보내지 않는다. 빈 목록을 주면 모델이 "여기 뭔가 있어야
    // 하는데" 로 읽고 없는 선을 지어낸다.
    ...(axis.line?.length ? { line: axis.line } : {}),
  };
}
