/**
 * 결제 전에 공개되는 몫이 하는 일 — 상품마다.
 *
 * 무료 공개분은 설명이 아니라 진단이다. 독자가 "이거 내 얘기인데" → "그럼 앞으로
 * 어떻게 된다는 거지" → "전체를 봐야겠다"로 움직여야 한다. 그 움직임을 만드는 재료가
 * 여기 있다: 독자가 입 밖에 내지 않은 질문, 독자가 실제로 겪었을 장면, 공개분이
 * 답하지 않고 남겨 둘 변수, 그리고 전체 풀이가 주는 것.
 *
 * **여기 적은 것은 표현의 재료지 명리 주장이 아니다.** 장면은 독자의 생활에서 고른
 * 것이고, 숨은 질문은 독자의 마음에서 고른 것이다. 명식에 대한 판단은 여전히
 * matched_rules 에서만 나온다 — 장면이 아무리 구체적이어도 규칙에 없는 성향을
 * 찌르지 않는다.
 */
export interface ProductPreview {
  /** 독자가 입 밖에 내는 질문 */
  surfaceQuestion: string;
  /** 그 뒤에 있는 진짜 질문. 공개분이 대신 말해 준다 */
  hiddenQuestion: string;
  /** 독자가 겪었을 법한 장면. 모델이 여기서 고르거나 같은 결로 새로 그린다 */
  scenes: string[];
  /**
   * 공개분이 가리키되 답하지 않는 핵심 변수. "…이냐가 아니라 …이냐" 꼴.
   * open_loop 의 원형이고, 잠긴 절이 그 답을 갖고 있어야 한다.
   */
  hiddenVariable: string;
  /** 전체 풀이에서 확인하는 것. 이어서 보기 창에 그대로 실린다 — 3~4개 */
  unlockReveals: string[];
}

