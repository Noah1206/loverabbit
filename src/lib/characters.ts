// 참여자 수 연출 — 날짜에 따라 조금씩 늘어나는 결정적 값
export function participantCount(id: string): number {
  const c = CHARACTERS[id];
  if (!c) return 0;
  const days = Math.floor(Date.now() / 86400000);
  return c.baseCount + ((days * 13 + c.baseCount) % 7) + (days % 97) * 3;
}
