// 분야별 리딩 컨셉 — 화면 구조는 모든 리딩이 똑같고, 옷만 분야마다 갈아입는다.
//
// 여기서 정하는 것: 그 분야를 읽어주는 화자(캐릭터), 인장 두 글자, 색,
// 장 제목, 장마다 화자가 던지는 한 마디(웹툰 말풍선).
// 여기서 정하지 않는 것: 레이아웃, 폰트 크기, 잠금 규칙 — 그건 뷰어가 갖는다.

export interface ReadingConcept {
  /** 이 분야를 읽어주는 화자 */
  narrator: string;
  /** 화자의 자리 — 표지의 부제 */
  shrine: string;
  /** 화자 이미지 (public/characters) */
  portrait: string;
  /** 인장에 새기는 두 글자 */
  seal: string;
  /** 표지 상단에 얹는 한 줄 */
  cover: string;
  /** 주조색 / 그라디언트 끝색 */
  ink: string;
  ink2: string;
  /** 장 제목 — 본문 장 수와 같은 순서 */
  chapters: string[];
  /** 장마다 화자가 던지는 말풍선 한 마디 */
  hooks: string[];
  /** 마지막 장(에필로그) 제목 */
  epilogue: string;
  /** 마지막 장에서 화자가 남기는 한 마디 */
  outro: string;
}

